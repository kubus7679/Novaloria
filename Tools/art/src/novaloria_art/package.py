"""Writes the FreeCol mod folder and its installable archive."""

from __future__ import annotations

import re
import shutil
import zipfile
from pathlib import Path

from .animation import SHIP_ANIMATION_OVERRIDES
from .manifest import RESOURCE_PREFIX, Manifest, canonical_path

MOD_ID = "novaloria-atlas"

MESSAGES = f"""\
mod.{MOD_ID}.name=Novaloria Atlas
mod.{MOD_ID}.shortDescription=Replaces FreeCol's map, unit, building and goods graphics with \
warmly lit 3D renderings in the spirit of We the People.
mod.{MOD_ID}.description=Original Blender renderings of terrain, forests, relief, units, ships, \
settlements, buildings and goods. Nation-specific originals share one architectural style.
mod.{MOD_ID}.license=GPL
"""

CREDITS = """\
Novaloria Atlas
===============

All images were rendered with Blender from procedurally generated models and materials
created for this mod. The look is inspired by the Civilization IV: Colonization mod
"We the People"; the mod contains no files from it or from Civilization IV.

Some layouts (tile footprints, sprite anchoring) follow the original FreeCol graphics,
which are licensed under the GNU General Public License. This mod is distributed under
the same license (see COPYING).
"""


def resource_lines(manifest: Manifest, produced: set[str]) -> list[str]:
    """Key mappings for every FreeCol key whose image the mod replaces."""
    included: dict[str, str] = {}
    aliases: dict[str, str] = {}
    for key, value in manifest.entries.items():
        override = SHIP_ANIMATION_OVERRIDES.get(key)
        if override is not None and override[1] in produced:
            included[key] = override[1]
            continue
        if value.startswith(RESOURCE_PREFIX):
            aliases[key] = value[len(RESOURCE_PREFIX) :]
            continue
        path = canonical_path(value)
        if path in produced:
            included[key] = path
    pending = dict(aliases)
    resolved: dict[str, str] = {}
    while True:
        ready = {key: target for key, target in pending.items() if target in included or target in resolved}
        if not ready:
            break
        resolved.update(ready)
        for key in ready:
            del pending[key]
    lines = [f"{key}={included[key]}" for key in manifest.entries if key in included]
    lines += [f"{key}={RESOURCE_PREFIX}{resolved[key]}" for key in manifest.entries if key in resolved]
    return lines


def write_mod(
    manifest: Manifest,
    staging: Path,
    mod_dir: Path,
    license_file: Path,
    archive: Path,
) -> list[str]:
    produced = {
        str(path.relative_to(staging))
        for path in staging.rglob("*")
        if path.is_file() and not re.search(r"\.size\d+\.", path.name)
    }
    lines = resource_lines(manifest, produced)
    resources_dir = mod_dir / "resources"
    if resources_dir.exists():
        shutil.rmtree(resources_dir)
    for file in sorted(path for path in staging.rglob("*") if path.is_file()):
        target = mod_dir / file.relative_to(staging)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(file, target)
    mod_xml = mod_dir / "mod.xml"
    if not mod_xml.exists():
        mod_xml.write_text(f'<mod id="{MOD_ID}"/>\n', encoding="utf-8")
    messages = mod_dir / "FreeColMessages.properties"
    if not messages.exists():
        messages.write_text(MESSAGES, encoding="utf-8")
    header = "# Generated by Tools/art (novaloria-art build); do not edit by hand.\n"
    (mod_dir / "resources.properties").write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    shutil.copyfile(license_file, mod_dir / "COPYING")
    (mod_dir / "CREDITS.txt").write_text(CREDITS, encoding="utf-8")
    for stale in ("FreeCol-COPYING",):
        (mod_dir / stale).unlink(missing_ok=True)
    write_archive(mod_dir, archive)
    return lines


def write_archive(mod_dir: Path, archive: Path) -> None:
    """Root-level layout with ``mod.xml`` first: FreeCol derives the base folder from the first entry."""
    archive.unlink(missing_ok=True)
    files = sorted(path for path in mod_dir.rglob("*") if path.is_file() and path.name != ".DS_Store")
    files.sort(key=lambda path: path.name != "mod.xml")
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as bundle:
        for file in files:
            bundle.write(file, file.relative_to(mod_dir).as_posix())
